create table if not exists public.ar_photo_pending (
  id bigint generated by default as identity primary key,
  item_id bigint not null check (item_id > 0),
  name text not null check (char_length(name) between 1 and 250),
  img text not null check (char_length(img) between 5 and 200),
  by_id uuid not null,
  by_name text not null default '' check (char_length(by_name) <= 120),
  live boolean not null default false,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'replaced')),
  at timestamptz not null default now(),
  decided_at timestamptz,
  unique (item_id, img)
);
create unique index if not exists ar_photo_pending_one on public.ar_photo_pending (item_id) where status = 'pending';
alter table public.ar_photo_pending enable row level security;

-- the owner decides; an active user may see what waits (so the one who took a photo sees that it arrived). Nobody writes here from a page.
