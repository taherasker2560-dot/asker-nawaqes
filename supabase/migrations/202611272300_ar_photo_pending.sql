create or replace function public.ar_photo_submit(p_item bigint, p_img text, p_by uuid)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare v_name text; v_by text; v_id bigint;
begin
  if p_item is null or p_item <= 0 or p_img is null or p_by is null then return jsonb_build_object('ok', false); end if;
  select name into v_name from public.ar_store_items where id = p_item;
  if v_name is null then select name into v_name from public.ar_photo_wanted where item_id = p_item; end if;
  select name into v_by from public.ar_staff where user_id = p_by;
  update public.ar_photo_pending set status = 'replaced', decided_at = now() where item_id = p_item and status = 'pending';
  insert into public.ar_photo_pending (item_id, name, img, by_id, by_name)
    values (p_item, left(coalesce(nullif(btrim(v_name), ''), p_item::text), 250), p_img, p_by, left(coalesce(v_by, ''), 120))
    returning id into v_id;
  return jsonb_build_object('ok', true, 'id', v_id);
end $function$;
revoke all on function public.ar_photo_submit(bigint, text, uuid) from public, anon, authenticated;
grant execute on function public.ar_photo_submit(bigint, text, uuid) to service_role;

create or replace function public.ar_photo_decide(p_id bigint, p_ok boolean)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare v record;
begin
  if (select auth.uid()) is distinct from 'ff6c33dc-9dc5-4e2f-95bb-5d449e231f1c'::uuid then raise exception 'owner only' using errcode = '42501'; end if;
  if p_ok is null then return jsonb_build_object('ok', false, 'error', 'no_answer'); end if;
  select * into v from public.ar_photo_pending where id = p_id and status = 'pending' for update;
  if not found then return jsonb_build_object('ok', false, 'error', 'gone'); end if;
  update public.ar_photo_pending set status = case when p_ok then 'approved' else 'rejected' end, decided_at = now() where id = v.id;
  if p_ok then
    insert into public.ar_store_edits (item_id, img, img_off, updated_at, updated_by, photo_ok_at) values (v.item_id, v.img, false, now(), v.by_id, now())
    on conflict (item_id) do update set img = excluded.img, img_off = false, updated_at = excluded.updated_at, updated_by = excluded.updated_by, photo_ok_at = excluded.photo_ok_at;
  else
    -- one that was already shown comes off; a photo put on the item since then is not touched
    update public.ar_store_edits set img = null, img_off = false, updated_by = null, photo_ok_at = null, updated_at = now() where item_id = v.item_id and img = v.img;
    insert into public.ar_photo_wanted (item_id, name, why, added_at, removed_at) values (v.item_id, v.name, 'retake', now(), null)
    on conflict (item_id) do update set name = excluded.name, why = 'retake', added_at = excluded.added_at, removed_at = null;
  end if;
  return jsonb_build_object('ok', true);
end $function$;
revoke all on function public.ar_photo_decide(bigint, boolean) from public, anon;
grant execute on function public.ar_photo_decide(bigint, boolean) to authenticated;

-- a user's own write (the page, or anything signed in as them) never puts a new photo on an item; taking one off or putting the site's own back still works
create or replace function public.ar_photo_guard()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
declare v_img text; v_by uuid;
begin
  if auth.uid() is null or auth.uid() = 'ff6c33dc-9dc5-4e2f-95bb-5d449e231f1c'::uuid then return new; end if;
  if new.img is null then return new; end if;
  if tg_op = 'UPDATE' then
    if new.img is distinct from old.img then new.img := old.img; new.updated_by := old.updated_by; end if;
  else
    -- an upsert comes here first, and what is left in the row here is what its update takes: so the photo already there is kept, not wiped
    select img, updated_by into v_img, v_by from public.ar_store_edits where item_id = new.item_id;
    if new.img is distinct from v_img then new.img := v_img; new.updated_by := v_by; end if;
  end if;
  return new;
end $function$;
revoke all on function public.ar_photo_guard() from public, anon, authenticated;
drop trigger if exists ar_store_edits_photo_guard on public.ar_store_edits;
create trigger ar_store_edits_photo_guard before insert or update on public.ar_store_edits
  for each row execute function public.ar_photo_guard();

-- a photo that does go on an item (his own) ends whatever still waited for it
create or replace function public.ar_photo_replaces()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
begin
  if new.img is null then return null; end if;
  if tg_op = 'UPDATE' then
    if new.img is not distinct from old.img then return null; end if;
  end if;
  update public.ar_photo_pending set status = 'replaced', decided_at = now() where item_id = new.item_id and status = 'pending' and img <> new.img;
  return null;
end $function$;
revoke all on function public.ar_photo_replaces() from public, anon, authenticated;
drop trigger if exists ar_store_edits_photo_replaces on public.ar_store_edits;
create trigger ar_store_edits_photo_replaces after insert or update of img on public.ar_store_edits
  for each row execute function public.ar_photo_replaces();

-- the photos users already put on items since a moment (his «صور النهارده تظهرلك تراجعها»): listed for his review and left shown. Safe to run again: it never lists a photo twice or one he decided
create or replace function public.ar_photo_take_shown(p_since timestamptz)
returns integer
language sql
security definer
set search_path to ''
as $function$
  with put as (
    insert into public.ar_photo_pending (item_id, name, img, by_id, by_name, live, at)
    select e.item_id, left(coalesce(nullif(btrim(i.name), ''), e.item_id::text), 250), e.img, e.updated_by, left(coalesce(s.name, ''), 120), true, e.updated_at
    from public.ar_store_edits e
    join public.ar_staff s on s.user_id = e.updated_by
    left join public.ar_store_items i on i.id = e.item_id
    where e.img is not null and not e.img_off and e.photo_ok_at is null and e.updated_at >= p_since
      and e.updated_by <> 'ff6c33dc-9dc5-4e2f-95bb-5d449e231f1c'::uuid
      and not exists (select 1 from public.ar_photo_pending p where p.item_id = e.item_id and (p.img = e.img or p.status = 'pending'))
    returning 1
  )
  select count(*)::integer from put;
$function$;
revoke all on function public.ar_photo_take_shown(timestamptz) from public, anon, authenticated;

