create table if not exists public.ar_photo_wanted (
  item_id bigint primary key check (item_id > 0),
  name text not null check (char_length(name) between 1 and 250),
  why text not null default 'none' check (why in ('none', 'picked')),
  added_at timestamptz not null default now(),
  removed_at timestamptz
);
alter table public.ar_photo_wanted enable row level security;

drop policy if exists "Owner ar photo wanted" on public.ar_photo_wanted;
create policy "Owner ar photo wanted" on public.ar_photo_wanted for all to authenticated
  using ((select auth.uid()) = 'ff6c33dc-9dc5-4e2f-95bb-5d449e231f1c'::uuid)
  with check ((select auth.uid()) = 'ff6c33dc-9dc5-4e2f-95bb-5d449e231f1c'::uuid);
drop policy if exists "Staff reads ar photo wanted" on public.ar_photo_wanted;
create policy "Staff reads ar photo wanted" on public.ar_photo_wanted for select to authenticated
